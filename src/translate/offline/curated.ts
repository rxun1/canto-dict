// phrase_map, where it wins over the pairs reversed from Kaifangcidian and Wiktionary. Pure data:
// no imports, so data-pipeline can compile it (like src/jyutping and src/script).
//
// Mandarin is written in simplified characters, as users type it; the pipeline converts it with
// OpenCC cn→t, the app's toTrad, so the keys match what substitution looks up. Cantonese is written
// in the Hong Kong spellings canto.db uses (words.hk forms: 嘅 係 冇 佢 喺 睇 嗰 啲), so Jyutping
// finds the words.
//
// Substitution takes the longest match (P3-T4), so a longer key shields the words inside it: 目的
// keeps its 的 from 的 → 嘅, 其他 its 他 from 他 → 佢. Identity pairs below exist only for that.
// Grammar that needs reordering (比, 先, 了, 在 + verb, A-not-A) is left to the reorder rules (P3-T5).

